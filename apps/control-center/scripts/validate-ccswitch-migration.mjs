#!/usr/bin/env node

import { createHash } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  CCSWITCH_ALLOWED_STATUSES,
  CCSWITCH_CAPABILITY_GROUPS,
  CCSWITCH_UPSTREAM,
  ccSwitchCapabilityEntries,
} from "../src/ccswitch/capability-map.mjs";

const appRoot = fileURLToPath(new URL("..", import.meta.url));
const repoRoot = resolve(appRoot, "..", "..");
const ledgerPath = resolve(repoRoot, "proposals", "ccswitch-3.18.0-capability-ledger.md");

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function normalizeGeneratedLedger(text) {
  return String(text ?? "").replaceAll("\r\n", "\n").replaceAll("\r", "\n");
}

function escapeCell(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\r", "")
    .replaceAll("\n", "<br>");
}

function extractInvokeRegistry(source) {
  const block = source.match(/invoke_handler\s*\(\s*tauri::generate_handler!\[(?<body>[\s\S]*?)\]\s*\)/)?.groups?.body;
  if (!block) throw new Error("CC-Switch invoke_handler registry was not found");
  const entries = [];
  for (const match of block.matchAll(/(?:(commands)::)?([A-Za-z_][A-Za-z0-9_]*)\s*,/g)) {
    entries.push({ command: match[2], namespaced: match[1] === "commands" });
  }
  return entries;
}

export function compareCommandCoverage(registryNames, mappedEntries) {
  const mappedNames = mappedEntries.map((item) => typeof item === "string" ? item : item.command);
  const mappedSet = new Set(mappedNames);
  const registrySet = new Set(registryNames);
  return {
    missing: registryNames.filter((command) => !mappedSet.has(command)),
    unknown: mappedNames.filter((command) => !registrySet.has(command)),
    duplicates: mappedNames.filter((command, index) => mappedNames.indexOf(command) !== index),
    orderMatches: registryNames.length === mappedNames.length && registryNames.every((command, index) => mappedNames[index] === command),
  };
}

async function exists(path) {
  try { await access(path); return true; } catch { return false; }
}

function renderLedger(entries) {
  const counts = Object.fromEntries([...CCSWITCH_ALLOWED_STATUSES].map((status) => [status, 0]));
  for (const entry of entries) counts[entry.status] += 1;
  const rows = entries.map((entry, index) => [
    index + 1,
    `\`${entry.command}\``,
    entry.group,
    entry.status,
    entry.implementation.map((item) => `\`${item}\``).join("<br>"),
    entry.api.map((item) => `\`${item}\``).join("<br>"),
    entry.ui.join("<br>"),
    entry.tests.map((item) => `\`${item}\``).join("<br>"),
    entry.boundary || "-",
  ].map(escapeCell).join(" | "));

  const raw = `<!-- Generated by apps/control-center/scripts/validate-ccswitch-migration.mjs. Do not edit by hand. -->
# CC-Switch 3.18.0 能力迁移账本

## 真源

- 上游：\`${CCSWITCH_UPSTREAM.repository}\` \`${CCSWITCH_UPSTREAM.version}\`
- 命令注册表：\`${CCSWITCH_UPSTREAM.registry}\`
- 注册表 SHA-256：\`${CCSWITCH_UPSTREAM.registrySha256}\`
- 注册入口：**${entries.length}**（\`${CCSWITCH_UPSTREAM.namespacedCommandCount}\` 个 \`commands::*\` + \`update_tray_menu\`）
- 冻结基线：**已按上述哈希锁定**；逐命令清单显式保存在 \`capability-map.mjs\`
- 实时复核：校验时若存在上游 scratch，会额外核对哈希、入口数量和逐命令覆盖；该附加结果不改变本生成文件

## 状态

| 状态 | 数量 | 含义 |
|---|---:|---|
| \`equivalent\` | ${counts.equivalent} | 514cc 有真实服务/API/UI/自动化证据，核心行为等价 |
| \`adapted\` | ${counts.adapted} | 能力由 514cc 既有架构承接，边界列明语义差异 |
| \`blocked_external_trust\` | ${counts.blocked_external_trust} | 只因外部信任材料缺失而 fail-closed，禁止伪造上线 |

校验器拒绝未映射命令、重复命令、未知状态、失效证据路径、上游注册表漂移和本文件生成漂移。

## 逐命令映射

| # | 上游 command | 能力组 | 状态 | 514cc 服务 | API / IPC | 可见入口 | 自动化证据 | 边界 |
|---:|---|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
  return normalizeGeneratedLedger(raw);
}

export async function validateCcSwitchMigration({
  write = false,
  registryPath = resolve(repoRoot, CCSWITCH_UPSTREAM.registry),
  ledgerPath: ledgerPathOverride,
} = {}) {
  const targetLedger = ledgerPathOverride || ledgerPath;
  const errors = [];
  const entries = ccSwitchCapabilityEntries();
  const seen = new Map();

  for (const capability of CCSWITCH_CAPABILITY_GROUPS) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(capability.id)) errors.push(`invalid capability group id: ${capability.id}`);
    if (!CCSWITCH_ALLOWED_STATUSES.has(capability.status)) errors.push(`unknown status for ${capability.id}: ${capability.status}`);
    if (!capability.commands.length) errors.push(`empty capability group: ${capability.id}`);
    for (const command of capability.commands) {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(command)) errors.push(`invalid command name: ${command}`);
      if (seen.has(command)) errors.push(`duplicate command mapping: ${command} (${seen.get(command)}, ${capability.id})`);
      seen.set(command, capability.id);
    }
    for (const reference of [...capability.implementation, ...capability.tests]) {
      const path = resolve(repoRoot, String(reference).split("#", 1)[0]);
      if (!await exists(path)) errors.push(`missing evidence path for ${capability.id}: ${reference}`);
    }
    if (!capability.implementation.length || !capability.api.length || !capability.ui.length || !capability.tests.length) {
      errors.push(`incomplete evidence columns for ${capability.id}`);
    }
    if (capability.status !== "equivalent" && !capability.boundary) errors.push(`non-equivalent group has no boundary: ${capability.id}`);
  }

  if (entries.length !== CCSWITCH_UPSTREAM.commandCount) {
    errors.push(`frozen command map count is ${entries.length}, expected ${CCSWITCH_UPSTREAM.commandCount}`);
  }

  let registryVerified = false;
  if (await exists(registryPath)) {
    const source = await readFile(registryPath, "utf8");
    const digest = sha256(source);
    if (digest !== CCSWITCH_UPSTREAM.registrySha256) {
      errors.push(`upstream registry hash drift: ${digest}`);
    }
    const registry = extractInvokeRegistry(source);
    const namespaced = registry.filter((item) => item.namespaced).length;
    if (registry.length !== CCSWITCH_UPSTREAM.commandCount) errors.push(`upstream registry contains ${registry.length} entries`);
    if (namespaced !== CCSWITCH_UPSTREAM.namespacedCommandCount) errors.push(`upstream registry contains ${namespaced} commands::* entries`);
    const registryNames = registry.map((item) => item.command);
    const coverage = compareCommandCoverage(registryNames, entries);
    const { missing, unknown } = coverage;
    if (missing.length) errors.push(`unmapped upstream commands: ${missing.join(", ")}`);
    if (unknown.length) errors.push(`mapped commands absent upstream: ${unknown.join(", ")}`);
    if (coverage.duplicates.length) errors.push(`duplicate mapped commands: ${coverage.duplicates.join(", ")}`);
    registryVerified = true;
  }

  const rendered = renderLedger(entries);
  if (write) {
    await writeFile(targetLedger, rendered, "utf8");
  } else if (!await exists(targetLedger)) {
    errors.push(`generated ledger is missing: ${targetLedger}`);
  } else if (normalizeGeneratedLedger(await readFile(targetLedger, "utf8")) !== rendered) {
    errors.push("generated CC-Switch ledger is stale; run npm run sync:ccswitch-ledger");
  }

  return {
    valid: errors.length === 0,
    errors,
    commandCount: entries.length,
    namespacedCommandCount: CCSWITCH_UPSTREAM.namespacedCommandCount,
    registryVerified,
    ledgerPath: targetLedger,
    statuses: Object.fromEntries([...CCSWITCH_ALLOWED_STATUSES].map((status) => [status, entries.filter((item) => item.status === status).length])),
  };
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const result = await validateCcSwitchMigration({ write: process.argv.includes("--write") });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  if (!result.valid) process.exitCode = 1;
}
